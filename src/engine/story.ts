/**
 * История — один самодостаточный объект: описание, герои, главы и сам сценарий на ink.
 * В репозитории она лежит папкой src/stories/<id>/ (meta.json + story.ink + главы через INCLUDE),
 * а наружу уходит одним .json (npm run story:pack): его можно передать, поправить и загрузить
 * обратно кнопкой «Загрузить» на главном экране.
 */

export interface Cover {
  /** Градиент карточки: верхний и нижний цвет. */
  from: string;
  to: string;
  /** Крупный знак на карточке. */
  glyph: string;
}

export interface Character {
  /** id контакта из сценария (# contact: theo, ...), если персонаж пишет в чат. */
  id?: string;
  name: string;
  /** Кто это одной строкой: «подруга Рэя, прачечная 24/7». */
  role: string;
  /** Пара предложений для экрана истории. */
  about?: string;
  /** Цвет кружка. По умолчанию берётся из сценария. */
  color?: string;
  /**
   * Служебный контакт: заметки, пульт, банк, сервис. Пишет в чат, но героем не считается:
   * экран истории его не показывает, проверки story:lint не ждут от него голоса и арки.
   */
  service?: boolean;
  /**
   * Служебное, для автора и проверок: экран истории это не показывает.
   * Карточка голоса — по ней игрок узнаёт контакт без подписи.
   */
  voice?: Voice;
  /**
   * Служебное: функция в сюжете по главам, от какой главы действует.
   * [{ from: 1, role: "источник" }, { from: 8, role: "виновная" }] — на экран не попадает, иначе спойлер.
   */
  arc?: ArcStep[];
}

/** Карточка голоса контакта: поля и сколько их должно различаться — rules.md R-75. */
export interface Voice {
  /** Длина реплики в словах: «2–5». */
  length?: string;
  /** Регистр и знаки: «строчные, без точек». */
  case?: string;
  /** Эмодзи: «никогда» или «🙂 в конце». */
  emoji?: string;
  /** Словечко: «короче». */
  word?: string;
  /** Обращение к игроку: «ты» или «Вы». */
  address?: string;
  /** Чего хочет от игрока. */
  wants?: string;
}

export interface ArcStep {
  /** С какой главы (с 1). */
  from: number;
  role: string;
}

export interface ChapterInfo {
  title: string;
  /** Когда происходит: «ночь», «утро». */
  when?: string;
  about?: string;
}

export interface Story {
  format: 'relayer-story';
  version: 1;
  id: string;
  /** Надпись над названием: мир или сериал. */
  series?: string;
  title: string;
  /** Одна строка о чём это — она же на карточке. */
  tagline: string;
  /** Абзац-два: завязка без спойлеров. */
  synopsis?: string;
  /** Ревизия сценария: растёт с каждой выпущенной правкой текста. */
  revision?: number;
  /** Сколько минут занимает в режиме «по клику» — без ожиданий. */
  minutes?: number;
  /** Сколько дней идёт в реальном времени, с настоящими паузами. Дробное — меньше суток. */
  days?: number;
  /** Сколько первых глав бесплатно. Нет поля — бесплатны все. */
  free_chapters?: number;
  chapters?: ChapterInfo[];
  characters?: Character[];
  /** Чем эта история интересна: «ответы уходят в разные чаты». */
  features?: string[];
  /**
   * Затравки для карточки на главном: 2–3 коротких крючка из завязки и первой главы,
   * без спойлеров. Карточка показывает первые три; нет поля — карточка без них.
   */
  teasers?: string[];
  /**
   * Не показывать на главном и не класть в dist/stories/ для Pages. Команды story:* и проверки
   * историю видят; в игре она открывается по ?story=<id>, на главном — с ?all=1.
   */
  hidden?: boolean;
  cover: Cover;
  /** Сценарий на ink: главный файл (story.ink) или вся история одним текстом. */
  ink: string;
  /** Остальные файлы ink по именам из INCLUDE: { "ch01.ink": "…" }. */
  includes?: Record<string, string>;
  /** Откуда взялась: лежит в коде или загружена с устройства. Не хранится в файле. */
  origin: 'builtin' | 'upload';
}

/** То, что лежит в файле: то же самое, но без origin (и ink может жить отдельным .ink). */
export type StoryFile = Omit<Story, 'origin' | 'ink'> & { ink?: string };

export const DEFAULT_COVER: Cover = { from: '#334155', to: '#0f141b', glyph: '✳' };
